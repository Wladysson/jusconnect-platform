// Representa os tipos de mensagens suportados pelo chat
public enum MessageType {

    // Mensagem de texto
    TEXT,

    // Imagem
    IMAGE,

    // Documento ou arquivo
    FILE,

    // Áudio
    AUDIO,

    // Vídeo
    VIDEO,

    // Localização
    LOCATION,

    // Mensagem referente a evento do sistema
    SYSTEM

}